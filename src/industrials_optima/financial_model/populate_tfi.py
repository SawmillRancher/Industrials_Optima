"""Populate TFI International consolidated historicals (FY20-FY25) into the
template generated by the financial_model builder.

TFI International files as a Canadian foreign private issuer (Form 40-F,
CIK 0001588823) under IFRS. The populator combines two EDGAR data sources:

  1. The standardized ifrs-full tags from the Company Facts JSON API
     (data.sec.gov) for the consolidated income statement, cash flow
     statement, and balance sheet.
  2. The per-filing "Segment Reporting (Details)" rendered R-files
     (www.sec.gov/Archives/.../R??.htm) for per-segment revenue and
     operating income, since segment breakouts are not in the standard
     IFRS taxonomy.

Segment-structure mapping:
  - FY20-FY23: 4 reportable segments (Package and Courier, LTL,
    Truckload, Logistics) -> the template's legacy 4-segment block.
  - FY24-FY25: 3 reportable segments (LTL, Truckload, Logistics) ->
    the template's current 3-segment block. Package and Courier was
    rolled into LTL in the FY24 40-F (confirmed by the FY23 restated
    comparative, where LTL revenue jumped ~$580M = prior-year P&C).

Known data quirks the populator preserves as-tagged:
  - FY24 CashAndCashEquivalents is tagged as 0 in both the original and
    the FY25 40-F restated comparative. The actual year-end balance has
    to be entered manually from the BS in the 40-F PDF.
  - FY21 / FY22 FinanceCosts are tagged with a negative sign in TFI's
    XBRL (an inconsistency between filings). The populator takes abs()
    so "Interest expense" remains positive.
  - Standalone Goodwill is only tagged through FY22. FY23+ rolls into
    IntangibleAssetsAndGoodwill -- that combined value lands in the
    template's "Intangible assets, net" row.
"""

