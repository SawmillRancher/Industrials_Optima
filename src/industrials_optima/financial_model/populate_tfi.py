# Populated consolidated range. FY19 is included so the row 161-164 / 211
# y/y% formulas (e.g., =BE114/AZ114-1) have a populated prior-year cell to
# divide against — the alternative would be wrapping every consolidated y/y%
# formula in the source template with IFERROR.
FISCAL_YEARS = range(2019, 2026)


def populate(
    workbook_path: str | Path,
    *,
    years: Iterable[int] = FISCAL_YEARS,
    facts_cache: Path | None = None,
    segment_cache_dir: Path | None = None,
    skip_segments: bool = False,
) -> dict[tuple[int, int], float]:
    """Populate ``workbook_path`` in place with TFI's IFRS historicals.

    Returns a dict of ``{(year, row): value}`` actually written for the
    consolidated facts, so callers can audit coverage. Segment writes are
    reported separately via ``populate_segments``.
    """
    workbook_path = Path(workbook_path)
    facts = fetch_facts(cache_path=facts_cache)
    wb = load_workbook(workbook_path)
    ws = wb["Model"]

    written: dict[tuple[int, int], float] = {}
    for year in years:
        col = fy_total_col(year)
        for m in ALL_MAPPINGS:
            v = resolve_value(facts, m, year)
            if v is None:
                continue
            ws.cell(row=m.row, column=col).value = v
            written[(year, m.row)] = v

    wb.save(workbook_path)

    if not skip_segments:
        seg_written = populate_segments(
            workbook_path, segment_cache_dir=segment_cache_dir
        )
        populate.last_segment_writes = seg_written  # type: ignore[attr-defined]
    else:
        populate.last_segment_writes = {}  # type: ignore[attr-defined]

    populate.last_yoy_writes = add_yoy_formulas(workbook_path)  # type: ignore[attr-defined]

    if not skip_segments:
        populate.last_operational_writes = populate_segment_operational_detail(  # type: ignore[attr-defined]
            workbook_path, segment_cache_dir=segment_cache_dir,
        )
    else:
        populate.last_operational_writes = 0  # type: ignore[attr-defined]

    populate.last_forecast_writes = populate_forecast_drivers(workbook_path)  # type: ignore[attr-defined]

    return written


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Populate TFI International historicals into a model template."
    )
    parser.add_argument(
        "workbook",
        type=Path,
        help="Path to the TFI model .xlsx (will be modified in place).",
    )
    parser.add_argument(
        "--facts-cache",
        type=Path,
        default=None,
        help="Optional path to cache the EDGAR Company Facts JSON.",
    )
    parser.add_argument(
        "--segment-cache",
        type=Path,
        default=None,
        help="Optional directory to cache per-year segment R-files (segment_YYYY.htm).",
    )
    parser.add_argument(
        "--skip-segments",
        action="store_true",
        help="Skip parsing 40-F segment R-files; populate consolidated IS/CF/BS only.",
    )
    args = parser.parse_args(argv)

    written = populate(
        args.workbook,
        facts_cache=args.facts_cache,
        segment_cache_dir=args.segment_cache,
        skip_segments=args.skip_segments,
    )
    print(f"Consolidated: {len(written)} cells across {len({y for y, _ in written})} fiscal years.")
    by_year: dict[int, int] = {}
    for (y, _), _ in written.items():
        by_year[y] = by_year.get(y, 0) + 1
    for y in sorted(by_year):
        print(f"  FY{y}: {by_year[y]} cells")
    seg_written = getattr(populate, "last_segment_writes", {})
    if seg_written:
        seg_years = {y for y, _, _ in seg_written}
        print(f"Segments:     {len(seg_written)} cells across {len(seg_years)} fiscal years.")
        seg_by_year: dict[int, int] = {}
        for (y, _, _), _ in seg_written.items():
            seg_by_year[y] = seg_by_year.get(y, 0) + 1
        for y in sorted(seg_by_year):
            print(f"  FY{y}: {seg_by_year[y]} cells")
    yoy_written = getattr(populate, "last_yoy_writes", 0)
    if yoy_written:
        print(f"Formula completions: {yoy_written} cells (y/y% + margins + cross-block FY24)")
    op_written = getattr(populate, "last_operational_writes", 0)
    if op_written:
        print(f"Operational detail:  {op_written} cells (3-seg FY23 restated -> FY25)")
    fc_written = getattr(populate, "last_forecast_writes", 0)
    if fc_written:
        print(f"Forecast drivers:    {fc_written} cells (Q1/26 baseline + scenarios + wiring)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
