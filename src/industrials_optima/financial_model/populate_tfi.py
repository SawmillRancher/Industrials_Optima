def fetch_facts(cache_path: Path | None = None) -> dict:
    """Fetch the EDGAR XBRL Company Facts JSON for TFI International.

    If ``cache_path`` is provided and exists, it is read instead of going
    over the network. The fetched payload is written there on success.
    """
    if cache_path and cache_path.exists():
        return json.loads(cache_path.read_text())
    req = urllib.request.Request(FACTS_URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        payload = resp.read().decode("utf-8")
    if cache_path:
        cache_path.write_text(payload)
    return json.loads(payload)


