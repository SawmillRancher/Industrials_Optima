# Per the Moog template layout: FY10 sits at column G (index 7), each
# subsequent year occupies five columns (Q1..Q4 + FY total). The FY total
# column for fiscal year N is therefore at index 7 + 5*(N - 10).
def fy_total_col(fy: int) -> int:
    return 7 + 5 * (fy - 10)


# A single mapping entry from a template row to one (or more) ifrs-full tags.
@dataclass
class Mapping:
    row: int
    tags: tuple[str, ...]    # try each tag in order; first hit wins
    kind: str                 # "duration" (period-flow) or "instant" (point-in-time)
    scale: float = 1_000_000  # divide raw USD by this; use 1 for per-share, 1000 for share counts
    sign: int = 1             # multiply by this (use -1 to negate)
    abs_value: bool = False   # take abs() before scaling (for tags with inconsistent sign)


