# ---------------------------------------------------------------------------
# EDGAR fetcher
# ---------------------------------------------------------------------------

def fetch_facts(cache_path: Path | None = None) -> dict:
    """Fetch the EDGAR XBRL Company Facts JSON for TFI International.

    If ``cache_path`` is provided and exists, it is read instead of going
    over the network. The fetched payload is written there on success.
    """
    if cache_path and cache_path.exists():
        return json.loads(cache_path.read_text())
    req = urllib.request.Request(FACTS_URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        payload = resp.read().decode("utf-8")
    if cache_path:
        cache_path.write_text(payload)
    return json.loads(payload)


# ---------------------------------------------------------------------------
# Fact extraction
# ---------------------------------------------------------------------------

def _is_full_year_duration(entry: dict, year: int) -> bool:
    start = entry.get("start", "")
    end = entry.get("end", "")
    return (
        start == f"{year}-01-01"
        and end == f"{year}-12-31"
        and entry.get("fp") == "FY"
    )


def _is_year_end_instant(entry: dict, year: int) -> bool:
    return entry.get("end") == f"{year}-12-31" and entry.get("fp") == "FY"


def value_for_year(facts: dict, tag: str, year: int, kind: str) -> float | None:
    """Return the most-recently-filed value of ``tag`` for fiscal ``year``.

    ``kind`` is ``"duration"`` (period flow) or ``"instant"`` (balance).
    Returns ``None`` if no matching entry exists.
    """
    ifrs = facts.get("facts", {}).get("ifrs-full", {})
    if tag not in ifrs:
        return None
    units = ifrs[tag]["units"]
    # Prefer USD; fall back to USD/shares or shares for per-share/share-count tags.
    for unit_name in ("USD", "USD/shares", "shares"):
        if unit_name not in units:
            continue
        match_fn = _is_full_year_duration if kind == "duration" else _is_year_end_instant
        candidates = [e for e in units[unit_name] if match_fn(e, year)]
        if not candidates:
            continue
        # Pick the latest-filed entry (most recent restatement wins).
        best = max(candidates, key=lambda e: e.get("filed", ""))
        return float(best["val"])
    return None


def resolve_value(facts: dict, mapping: Mapping, year: int) -> float | None:
    """Walk a mapping's tag list, return the first hit with the scale/sign applied."""
    for tag in mapping.tags:
        raw = value_for_year(facts, tag, year, mapping.kind)
        if raw is None:
            continue
        if mapping.abs_value:
            raw = abs(raw)
        return mapping.sign * raw / mapping.scale
    return None


# ---------------------------------------------------------------------------
# Workbook write
# ---------------------------------------------------------------------------

FISCAL_YEARS = range(2020, 2026)


def populate(
    workbook_path: str | Path,
    *,
    years: Iterable[int] = FISCAL_YEARS,
    facts_cache: Path | None = None,
) -> dict[tuple[int, int], float]:
    """Populate ``workbook_path`` in place with TFI's IFRS historicals.

    Returns a dict of ``{(year, row): value}`` actually written, so callers
    can audit coverage.
    """
    workbook_path = Path(workbook_path)
    facts = fetch_facts(cache_path=facts_cache)
    wb = load_workbook(workbook_path)
    ws = wb["Model"]

    written: dict[tuple[int, int], float] = {}
    for year in years:
        col = fy_total_col(year)
        for m in ALL_MAPPINGS:
            v = resolve_value(facts, m, year)
            if v is None:
                continue
            ws.cell(row=m.row, column=col).value = v
            written[(year, m.row)] = v

    wb.save(workbook_path)
    return written


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Populate TFI International historicals into a model template."
    )
    parser.add_argument(
        "workbook",
        type=Path,
        help="Path to the TFI model .xlsx (will be modified in place).",
    )
    parser.add_argument(
        "--facts-cache",
        type=Path,
        default=None,
        help="Optional path to cache the EDGAR Company Facts JSON.",
    )
    args = parser.parse_args(argv)

    written = populate(args.workbook, facts_cache=args.facts_cache)
    print(f"Wrote {len(written)} cells across {len({y for y, _ in written})} fiscal years.")
    by_year: dict[int, int] = {}
    for (y, _), _ in written.items():
        by_year[y] = by_year.get(y, 0) + 1
    for y in sorted(by_year):
        print(f"  FY{y}: {by_year[y]} cells")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
