def fetch_segment_report(fy: int, cache_dir: Path | None = None) -> str:
    """Fetch the segment-results R-file HTML for fiscal year ``fy``.

    EDGAR rate-limits sequential requests; retry with exponential backoff
    on 503 up to four attempts.
    """
    acc, htm_name = SEGMENT_REPORT_FILES[fy]
    if cache_dir:
        cached = cache_dir / f"segment_{fy}.htm"
        if cached.exists():
            return cached.read_text()
    url = f"{EDGAR_FILING_BASE}/{acc.replace('-', '')}/{htm_name}"
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    delay = 2.0
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                text = resp.read().decode("utf-8")
            if cache_dir:
                cache_dir.mkdir(parents=True, exist_ok=True)
                (cache_dir / f"segment_{fy}.htm").write_text(text)
            return text
        except urllib.error.HTTPError as e:
            if e.code != 503 or attempt == 3:
                raise
            time.sleep(delay)
            delay *= 2
    raise RuntimeError(f"Unreachable: failed to fetch segment R-file for FY{fy}")


def _parse_cell(s: str) -> float | None:
    """Parse a numeric cell: '$ 6,913,039' / '(46,061)' / '$ (124)' / '—'."""
    if not s:
        return None
    s = s.replace("$", "").replace(",", "").strip()
    s = re.sub(r"\[[0-9,]+\]", "", s).strip()  # drop footnote markers [1], [2,3]
    if s in ("", "—", "-", "–"):
        return None
    neg = s.startswith("(") and s.endswith(")")
    if neg:
        s = s[1:-1].strip()
    try:
        v = float(s)
    except ValueError:
        return None
    return -v if neg else v


def parse_segment_html(html_text: str) -> tuple[list[int], dict[str, dict[str, list[float | None]]]]:
    """Parse a 40-F segment R-file. Returns ``(years, segments)`` where
    ``years`` is the column labels (most recent first) and ``segments`` maps
    each segment name (e.g. ``"Less-Than-Truckload"``) to ``{line_item:
    values_per_column}``.
    """
    html_text = re.sub(r"<style[^>]*>.*?</style>", "", html_text, flags=re.S)
    html_text = re.sub(r"<script[^>]*>.*?</script>", "", html_text, flags=re.S)

    rows: list[list[str]] = []
    for tr in re.finditer(r"<tr[^>]*>(.*?)</tr>", html_text, flags=re.S):
        cells: list[str] = []
        for td in re.finditer(r"<t[hd][^>]*>(.*?)</t[hd]>", tr.group(1), flags=re.S):
            txt = re.sub(r"<[^>]+>", " ", td.group(1))
            txt = html.unescape(txt).replace("\xa0", " ").strip()
            txt = re.sub(r"\s+", " ", txt)
            cells.append(txt)
        if cells:
            rows.append(cells)

    # Year columns appear in the first few header rows as 'Dec. 31, YYYY'.
    years: list[int] = []
    for row in rows[:5]:
        for cell in row:
            m = re.search(r"(20\d{2})", cell)
            if m and "Dec" in cell:
                y = int(m.group(1))
                if y not in years:
                    years.append(y)

    segments: dict[str, dict[str, list[float | None]]] = {"Total": {}}
    current = "Total"
    for row in rows:
        first = row[0] if row else ""
        if first.startswith("Operating Segments |"):
            current = first.split("|", 1)[1].strip()
            segments.setdefault(current, {})
            continue
        if first in ("Corporate", "Eliminations") and not any(
            re.search(r"\d", c) for c in row[1:3]
        ):
            current = first
            segments.setdefault(current, {})
            continue
        nums = [_parse_cell(c) for c in row[1:]]
        if any(n is not None for n in nums):
            segments[current][first] = nums
    return years, segments


def _values_by_year(years: list[int], vals: list[float | None]) -> dict[int, float]:
    """Strip empty cells, then positionally align remaining numeric cells with the year header."""
    filtered = [v for v in vals if v is not None]
    return {y: v for y, v in zip(years, filtered)}


def populate_segments(
    workbook_path: str | Path,
    *,
    segment_cache_dir: Path | None = None,
) -> dict[tuple[int, int, str], float]:
    """Populate segment P&L blocks (legacy FY20-FY23 + current FY24-FY25).

    Returns ``{(year, row, segment_name): value}``.
    """
    workbook_path = Path(workbook_path)
    wb = load_workbook(workbook_path)
    ws = wb["Model"]
    written: dict[tuple[int, int, str], float] = {}

    for idx, fy in enumerate(SEGMENT_REPORT_FILES):
        if idx > 0:
            # Pace successive EDGAR fetches; respects the public-data limit
            # and is a no-op when the cache already has the file.
            time.sleep(0.25)
        text = fetch_segment_report(fy, cache_dir=segment_cache_dir)
        years, segs = parse_segment_html(text)
        # Decide which block this filing belongs to based on its segment set.
        is_legacy = "Package and Courier" in segs
        seg_rows = LEGACY_SEGMENT_ROWS if is_legacy else CURRENT_SEGMENT_ROWS
        line_offsets = LEGACY_LINE_OFFSETS if is_legacy else CURRENT_LINE_OFFSETS

        # Each filing's current year always gets stamped; the FY20 filing is
        # also the only EDGAR source for FY19 segment values (its R-file has
        # FY20 + FY19 + FY18 columns), so harvest the prior-year column there
        # to unlock the FY20 segment y/y% calculations.
        target_years = [fy] + ([fy - 1] if fy == 2020 else [])

        for target_fy in target_years:
            col = fy_total_col(target_fy)
            for seg_name, seg_row in seg_rows.items():
                if seg_name not in segs:
                    continue
                for label, offset in line_offsets.items():
                    line_vals = segs[seg_name].get(label)
                    if not line_vals:
                        continue
                    vals_by_yr = _values_by_year(years, line_vals)
                    if target_fy not in vals_by_yr:
                        continue
                    # R-files report in $ thousands; template uses $ millions.
                    v = vals_by_yr[target_fy] / 1_000.0
                    ws.cell(row=seg_row + offset, column=col).value = v
                    written[(target_fy, seg_row + offset, seg_name)] = v

    wb.save(workbook_path)
    return written


# ---------------------------------------------------------------------------
# Formula completions
#
# The Moog source template carries formulas only for the year ranges Moog
# itself used (legacy block FY11-FY21/FY22, current block FY22-FY25). For
# TFI's data shape and reporting history we need to fill the gaps, point
# cross-block transitions at the legacy block (with P&C add-back for LTL),
# and repoint a couple of rows whose source formula targets an upstream
# cell TFI doesn't have data for.
#
# Categories below:
#   1. y/y% completions (covered Sales y/y% and EBIT y/y%)
#   2. Legacy Group Total SUM extensions (4 segments, through FY23)
#   3. Cross-block FY24 overrides for the current block (y/y% + Inc EBIT
#      + Group totals so the FY24 group y/y% has a real denominator)
#   4. Other derived metrics: legacy Op margin % gap-fill, current-block
#      cross-block Incremental EBIT, Adj EBIT % / Inc OP margin repointed
#      to GAAP EBIT (row 126) since TFI has no GAAP->Adj bridge.
#
# Backlog y/y%, book-to-bill, gross margin / R&D % / SG&A % / DIO / DPO
# are intentionally untouched -- TFI is a logistics business and either
# the metric isn't reported (backlog/B:B) or the underlying line item
# isn't broken out in the IFRS taxonomy (no COGS / R&D / SG&A split).
# ---------------------------------------------------------------------------

